// Token Radar's value model: a sealed snapshot in, a ranked board out.
//
// The board ranks pre-token protocols by an implied value the snapshot itself
// justifies. Nothing is hard-coded to a name: the base multiple is the median
// market-cap-to-TVL ratio of the protocols in the snapshot that already trade,
// and each category's factor is that category's own median ratio against the
// global one. A protocol is pre-token when its record carries no token at all
// (no market cap, no CoinGecko id, no symbol). Bridges, canonical bridges and
// restaked-BTC products are left out of the ranking because each is a wrapped
// or bridged form of a token that already trades; liquid staking and liquid
// restaking stay in, because those services commonly issue a governance token
// of their own. Centralised exchanges and versioned pools are left out too.
//
//   implied = tvl_usd x base_multiple x category_factor
//                     x growth(change_7d) x (0.6 + min(age_days, 1095) / 1095 x 0.4)
//   growth(p) is 1 + clamp(p, -60, 120) / 100 x 0.5 down to -20%; below
//   -20% the part under -20 is charged at full weight, so a -60% protocol
//   keeps half its multiple, not 70%.
//
// Age is the days since the protocol was first listed, the record of how long
// it has run with no token; an unlisted age counts as 365 days. The board
// holds 200 rows: every watchlist slug, plus the 160 highest-implied-value
// pre-token protocols outside it.

/** One protocol as the sealed snapshot records it. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, derived from the snapshot at run time. */
export interface ModelConstants {
  /** Median market-cap / TVL across the snapshot's tokenized protocols. */
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  /** The 7-day change below which the fall is charged at full weight. */
  growth_kink: number;
  /** The weight on the part of the fall below the kink. */
  growth_below_weight: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  /** Per-category multiple relative to the global one, 0.5..2, where the category has enough tokenized protocols to measure. */
  category_factors: Record<string, number>;
}

export const MODEL_VERSION = 'radar-2';
export const EARLY_ROWS = 160;
export const LIVE_ROWS = 24;

